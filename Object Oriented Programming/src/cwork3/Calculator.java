package cwork3;

public class Calculator {
    public int calculate(int a, int b) { 
        return a + b; 
    }
    public int calculate(int a, int b, int c) { 
        return a + b + c; 
    }
    public double calculate(double a, double b) { 
        return a + b; 
    }
    public int calculate(int a, int b, boolean multiply) { 
        return a * b; 
    }
}